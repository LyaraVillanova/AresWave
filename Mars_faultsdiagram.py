    dip_plot = dip
    if dip_plot < 0:
        dip_plot = -dip_plot
    if dip_plot > 90:
        dip_plot = 180 - dip_plot
        strike_plot = (strike_plot + 180) % 360.0
    rake_plot = ((rake + 180.0) % 360.0) - 180.0

    fig = beachball(
        [strike_plot, dip_plot, rake_plot],
        size=200,
        linewidth=1.2,
        facecolor="k"
    )

    fname = f"{event}_{model}_beachball_GMT.png"
    fig.savefig(os.path.join(outdir, fname),
                dpi=300, bbox_inches="tight")
    plt.close(fig)
